//go:build ignore

// Command gen regenerates the embedded time-zone tables used by package
// tzinfo. It downloads the CLDR windowsZones.xml mapping and the IANA tzdata
// zone.tab and backward files, then writes two compact TSV files:
//
//	windowszones.tsv  WindowsID <TAB> territory <TAB> IANA zone
//	zonecountry.tsv   IANA zone (canonical or alias) <TAB> ISO 3166-1 alpha-2
//
// Run from the tzinfo package directory:
//
//	go run gen/main.go
//
// or via go generate ./internal/tzinfo/ from the collector module root.
package main

import (
	"bufio"
	"bytes"
	"encoding/xml"
	"flag"
	"fmt"
	"io"
	"log"
	"net/http"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"
)

const (
	cldrURL     = "https://raw.githubusercontent.com/unicode-org/cldr/main/common/supplemental/windowsZones.xml"
	zoneTabURL  = "https://raw.githubusercontent.com/eggert/tz/main/zone.tab"
	backwardURL = "https://raw.githubusercontent.com/eggert/tz/main/backward"
)

func main() {
	out := flag.String("out", ".", "output directory")
	flag.Parse()

	cldr := fetch(cldrURL)
	zoneTab := fetch(zoneTabURL)
	backward := fetch(backwardURL)

	zoneCountry := parseZoneTab(zoneTab)
	links := parseBackward(backward)

	// resolve follows alias chains to a zone listed in zone.tab, or returns "".
	resolve := func(name string) string {
		for i := 0; i < 10; i++ {
			if _, ok := zoneCountry[name]; ok {
				return name
			}
			next, ok := links[name]
			if !ok {
				return ""
			}
			name = next
		}
		return ""
	}

	// zonecountry.tsv: every zone.tab zone plus every backward alias whose
	// target resolves to a zone.tab zone. zone.tab entries always win, so
	// e.g. Europe/Amsterdam stays NL even though tzdata links it to Brussels.
	countries := map[string]string{}
	for z, cc := range zoneCountry {
		countries[z] = cc
	}
	for alias := range links {
		if _, ok := countries[alias]; ok {
			continue
		}
		if t := resolve(alias); t != "" {
			countries[alias] = zoneCountry[t]
		}
	}

	// windowszones.tsv: CLDR mapZone rows. CLDR uses its own (sometimes
	// legacy) zone IDs such as Asia/Calcutta; canonicalise them to the
	// zone.tab name when the CLDR name is only a backward alias.
	var doc struct {
		Zones []struct {
			Other     string `xml:"other,attr"`
			Territory string `xml:"territory,attr"`
			Type      string `xml:"type,attr"`
		} `xml:"windowsZones>mapTimezones>mapZone"`
	}
	if err := xml.Unmarshal(cldr, &doc); err != nil {
		log.Fatalf("parse windowsZones.xml: %v", err)
	}
	var wz []string
	for _, z := range doc.Zones {
		fields := strings.Fields(z.Type)
		if z.Other == "" || z.Territory == "" || len(fields) == 0 {
			continue
		}
		zone := fields[0]
		if _, ok := zoneCountry[zone]; !ok {
			if t := resolve(zone); t != "" {
				zone = t
			}
		}
		wz = append(wz, z.Other+"\t"+z.Territory+"\t"+zone)
	}
	if len(wz) < 100 || len(countries) < 300 {
		log.Fatalf("suspiciously small tables: %d windows rows, %d zones", len(wz), len(countries))
	}
	sort.Strings(wz)

	var cz []string
	for z, cc := range countries {
		cz = append(cz, z+"\t"+cc)
	}
	sort.Strings(cz)

	write(filepath.Join(*out, "windowszones.tsv"),
		"# Generated by gen/main.go from CLDR windowsZones.xml ("+cldrURL+"). DO NOT EDIT.\n"+
			"# WindowsID\tterritory\tIANA (001 = golden zone)\n", wz)
	write(filepath.Join(*out, "zonecountry.tsv"),
		"# Generated by gen/main.go from IANA tzdata zone.tab + backward ("+zoneTabURL+", "+backwardURL+"). DO NOT EDIT.\n"+
			"# IANA zone or alias\tISO 3166-1 alpha-2\n", cz)
	log.Printf("wrote %d windows rows, %d zone->country rows", len(wz), len(cz))
}

func fetch(url string) []byte {
	c := &http.Client{Timeout: 60 * time.Second}
	resp, err := c.Get(url)
	if err != nil {
		log.Fatalf("GET %s: %v", url, err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("GET %s: %s", url, resp.Status)
	}
	b, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatalf("read %s: %v", url, err)
	}
	return b
}

// parseZoneTab returns zone -> country code from zone.tab.
func parseZoneTab(b []byte) map[string]string {
	m := map[string]string{}
	sc := bufio.NewScanner(bytes.NewReader(b))
	for sc.Scan() {
		line := sc.Text()
		if line == "" || line[0] == '#' {
			continue
		}
		f := strings.Split(line, "\t")
		if len(f) < 3 || len(f[0]) != 2 {
			continue
		}
		m[f[2]] = strings.ToUpper(f[0])
	}
	return m
}

// parseBackward returns alias -> target from "Link TARGET ALIAS" lines.
func parseBackward(b []byte) map[string]string {
	m := map[string]string{}
	sc := bufio.NewScanner(bytes.NewReader(b))
	for sc.Scan() {
		line := sc.Text()
		if i := strings.IndexByte(line, '#'); i >= 0 {
			line = line[:i]
		}
		f := strings.Fields(line)
		if len(f) >= 3 && f[0] == "Link" {
			m[f[2]] = f[1]
		}
	}
	return m
}

func write(path, header string, rows []string) {
	var buf bytes.Buffer
	buf.WriteString(header)
	for _, r := range rows {
		buf.WriteString(r)
		buf.WriteByte('\n')
	}
	if err := os.WriteFile(path, buf.Bytes(), 0o644); err != nil {
		log.Fatalf("write %s: %v", path, err)
	}
	fmt.Fprintf(os.Stderr, "%s: %d bytes\n", path, buf.Len())
}
